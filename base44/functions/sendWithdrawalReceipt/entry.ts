import { createClientFromRequest } from 'npm:@base44/sdk@0.8.49';

// Emails a "Rotary Inc" withdrawal receipt to the user's registered email
// after a withdrawal attempt — on success OR failure — so the user always
// gets a receipt. Also returns the generated payment-order id + timestamp
// so the client's on-screen receipt matches the emailed one.
const CHAIN_NAME = { bnb: 'BNB Smart Chain', ethereum: 'Ethereum', polygon: 'Polygon' };

function ordinal(n) {
  const s = ['th', 'st', 'nd', 'rd'];
  const v = n % 100;
  return n + (s[(v - 20) % 10] || s[v] || s[0]);
}

function fmtDate(iso) {
  const d = new Date(iso);
  const month = d.toLocaleString('en-US', { month: 'long' });
  return `${month} ${ordinal(d.getDate())} ${d.getFullYear()}`;
}

function escapeHtml(str) {
  return String(str ?? '').replace(/[&<>"']/g, (c) => ({
    '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;',
  }[c]));
}

export default async function(req) {
  try {
    const base44 = createClientFromRequest(req);
    const user = await base44.auth.me();
    if (!user) return Response.json({ error: 'Unauthorized' }, { status: 401 });
    if (!user.email) return Response.json({ error: 'No email on file for this user' }, { status: 400 });

    const body = await req.json();
    const { success, amount, token, chain, txHash, toAddress, error } = body;
    if (amount == null || !token || !chain) {
      return Response.json({ error: 'amount, token and chain are required' }, { status: 400 });
    }

    const paymentOrderId = crypto.randomUUID();
    const date = new Date().toISOString();
    const chainName = CHAIN_NAME[chain] || chain;
    const statusLabel = success ? 'Successful' : 'Failed';
    const statusColor = success ? '#16A34A' : '#DC2626';
    const txDisplay = txHash ? `${txHash.slice(0, 10)}…${txHash.slice(-8)}` : 'N/A';
    const amountStr = Number(amount || 0).toLocaleString('en-US', { minimumFractionDigits: 2, maximumFractionDigits: 2 });
    const toDisplay = toAddress ? `${toAddress.slice(0, 10)}…${toAddress.slice(-8)}` : '—';

    const html = `
<!DOCTYPE html><html><body style="margin:0;padding:0;background:#0b0b0c;font-family:-apple-system,BlinkMacSystemFont,'Segoe UI',Roboto,Helvetica,Arial,sans-serif;">
  <div style="max-width:420px;margin:24px auto;background:#1c1c1e;border-radius:20px;padding:36px 32px;color:#ffffff;">
    <div style="text-align:center;">
      <div style="width:52px;height:52px;border-radius:14px;background:#000000;color:#ffffff;font-size:28px;font-weight:700;line-height:52px;margin:0 auto 16px;">r</div>
      <p style="margin:0;color:#A0A0A0;font-size:15px;">Receipt from Rotary Inc</p>
      <p style="margin:6px 0 0;color:#808080;font-size:13px;">${fmtDate(date)}</p>
      <p style="display:inline-block;margin:14px 0 0;padding:4px 12px;border-radius:9999px;background:${statusColor}22;color:${statusColor};font-size:12px;font-weight:600;letter-spacing:.3px;">${statusLabel}</p>
    </div>

    <div style="margin:28px 0 20px;">
      <p style="margin:0;color:#A0A0A0;font-size:13px;">Amount Paid</p>
      <p style="margin:8px 0 0;font-size:32px;font-weight:700;letter-spacing:-.5px;">${amountStr} ${escapeHtml(token)}</p>
    </div>

    <div style="height:1px;background:#2e2e30;margin:20px 0;"></div>

    <div style="margin:16px 0;">
      <p style="margin:0;color:#A0A0A0;font-size:13px;">Payment Order ID</p>
      <p style="margin:6px 0 0;font-size:14px;word-break:break-all;">${escapeHtml(paymentOrderId)}</p>
    </div>

    <div style="margin:16px 0;">
      <p style="margin:0;color:#A0A0A0;font-size:13px;">Transaction</p>
      <p style="margin:6px 0 0;font-size:14px;">${txHash ? escapeHtml(txDisplay) : 'N/A'}</p>
    </div>

    <div style="margin:16px 0;">
      <p style="margin:0;color:#A0A0A0;font-size:13px;">Payment Method</p>
      <p style="margin:6px 0 0;font-size:14px;">${escapeHtml(token)} on ${escapeHtml(chainName)}</p>
    </div>

    <div style="margin:16px 0;">
      <p style="margin:0;color:#A0A0A0;font-size:13px;">Destination</p>
      <p style="margin:6px 0 0;font-size:14px;word-break:break-all;">${escapeHtml(toDisplay)}</p>
    </div>

    ${error ? `<div style="margin:16px 0;"><p style="margin:0;color:#A0A0A0;font-size:13px;">Reason</p><p style="margin:6px 0 0;font-size:14px;color:#F87171;">${escapeHtml(error)}</p></div>` : ''}

    <div style="height:1px;background:#2e2e30;margin:20px 0;"></div>
    <p style="margin:0;text-align:center;color:#808080;font-size:12px;line-height:1.5;">
      This receipt was generated by Rotary Inc. ${success ? 'Your withdrawal has been broadcast to the network.' : 'Your withdrawal could not be completed.'}<br/>Service Above Self.
    </p>
  </div>
</body></html>`;

    await base44.asServiceRole.integrations.Core.SendEmail({
      to: user.email,
      subject: `Rotary Inc — Withdrawal ${statusLabel}`,
      html,
    });

    return Response.json({ paymentOrderId, date, sent: true });
  } catch (error) {
    return Response.json({ error: error.message }, { status: 500 });
  }
}